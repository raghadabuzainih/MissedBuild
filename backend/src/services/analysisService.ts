// The evidence exactly as it is encoded into the prompt. The map is
// {ref, text} (mapPromptCost) and source files are {ref, text} pairs in this
// key order (filePromptCost): their costs are exact.
function promptData(evidence: AnalysisEvidence) {
  const readme = evidence.readme?.content ?? null;
  return {
    repository: {
      name: evidence.fullName,
      description: evidence.description,
      language: evidence.language,
      topics: evidence.topics,
    },
    map: evidence.map ? { ref: evidence.map.ref, text: evidence.map.text } : null,
    readme: readme === null ? null : { ref: "readme", text: readme.slice(0, PROMPT_README_CHARS) },
    openIssues: evidence.issues.filter((issue) => issue.state === "open").map(issuePrompt),
    // closedAs: "completed" (done), "not_planned" (declined) or "unknown".
    closedIssues: evidence.issues
      .filter((issue) => issue.state === "closed")
      .map((issue) => ({ ...issuePrompt(issue), closedAs: issue.stateReason === "not_planned" ? "not_planned" : issue.stateReason === "completed" ? "completed" : "unknown" })),
    files: evidence.files.map((file) => ({ ref: file.ref, text: file.rendered })),
  };
}

