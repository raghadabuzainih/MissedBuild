const normalize = (s: string) => s.replace(/\s+/g, " ").trim().toLowerCase();

// A code block normalized like excerpts are, with the line each part starts on.
type IndexedCode = { text: string; lines: { offset: number; line: number }[] };

function indexCode(startLine: number, code: string): IndexedCode {
  const lines: IndexedCode["lines"] = [];
  let text = "";
  code.split("\n").forEach((raw, i) => {
    const line = normalize(raw);
    if (!line) return;
    if (text) text += " ";
    lines.push({ offset: text.length, line: startLine + i });
    text += line;
  });
  return { text, lines };
}

type FileSource = { kind: "file"; url: string; path: string; code: IndexedCode[]; outline: { line: number; text: string }[] };
type TextSource = {
  kind: "text";
  source: AnalysisSource;
  text: string;
  // Closed issues are history: never evidence of a current problem or gap.
  closedIssue: boolean;
};
// Excerpts are checked against repository text only: code blocks and single
// outline lines, never our markers or L<n> labels.
type KnownSource = TextSource | FileSource;

// The only citable sources: this repository's map, README, issues and the
// source files that were sent.
function knownSources(evidence: AnalysisEvidence): Map<string, KnownSource> {
  const known = new Map<string, KnownSource>();
  if (evidence.map) {
    known.set("map", { kind: "text", source: { type: "structure", url: evidence.map.htmlUrl }, text: normalize(evidence.map.text), closedIssue: false });
  }
  if (evidence.readme) {
    known.set("readme", { kind: "text", source: { type: "readme", url: evidence.readme.url }, text: normalize(evidence.readme.content), closedIssue: false });
  }
  for (const issue of evidence.issues) {
    known.set(`issue#${issue.number}`, {
      kind: "text",
      source: { type: "issue", url: issue.htmlUrl, issueNumber: issue.number },
      text: normalize(`${issue.title} ${issue.body ?? ""}`),
      closedIssue: issue.state === "closed",
    });
  }
  for (const file of evidence.files) {
    known.set(file.ref, {
      kind: "file",
      url: file.htmlUrl,
      path: file.path,
      code: file.segments.flatMap((s) => (s.kind === "code" ? [indexCode(s.startLine, s.text)] : [])),
      outline: file.segments.flatMap((s) => (s.kind === "outline" ? [{ line: s.line, text: normalize(s.text) }] : [])),
    });
  }
  return known;
}

// Where an excerpt appears in a sent file: in a code block (shows behavior)
// or only in an outline line (shows that a declaration exists).
function findInFile(file: FileSource, excerpt: string): { line: number; inCode: boolean } | null {
  const needle = normalize(excerpt);
  if (!needle) return null;
  for (const block of file.code) {
    const at = block.text.indexOf(needle);
    if (at === -1) continue;
    let line = block.lines[0].line;
    for (const part of block.lines) {
      if (part.offset > at) break;
      line = part.line;
    }
    return { line, inCode: true };
  }
  const entry = file.outline.find((e) => e.text.includes(needle));
  return entry ? { line: entry.line, inCode: false } : null;
}

// Accepts "map", "readme", "issue#12", "issue 12", "issue:12", "#12",
// "file:<path>" and the bare path of a sent file. File paths keep their case.
function toRef(ref: string, known: Map<string, KnownSource>): string {
  const trimmed = ref.trim();
  const file = /^file\s*:\s*(.+)$/i.exec(trimmed);
  if (file) return `file:${file[1].trim().replace(/^\.\//, "")}`;
  const bare = `file:${trimmed.replace(/^\.\//, "")}`;
  if (known.get(bare)?.kind === "file") return bare;
  const lower = trimmed.toLowerCase();
  const issue = /^(?:issue\s*[#:]?\s*|#)(\d+)$/.exec(lower);
  return issue ? `issue#${issue[1]}` : lower;
}

type Resolved = {
  sources: AnalysisSource[];
  // At least one kept source can carry a fact: the map, the README, an issue,
  // or a file with an excerpt found in a code block.
  supportsFact: boolean;
  // At least one kept source can show a current gap: an open issue, or the
  // README with a verified excerpt. Absence from the code or map never does.
  supportsGap: boolean;
  // Sources dropped because they were closed issues.
  closedDropped: number;
};

function resolveSources(raw: unknown[], known: Map<string, KnownSource>, options: { currentOnly: boolean }): Resolved {
  const resolved = new Map<string, { source: AnalysisSource; strong: boolean; gap: boolean }>();
  let closedDropped = 0;
  for (const item of raw) {
    const parsed = rawSource.safeParse(item);
    if (!parsed.success) continue;
    const match = known.get(toRef(parsed.data.ref, known));
    if (!match) continue;
    const excerpt = parsed.data.excerpt?.trim().slice(0, MAX_EXCERPT_CHARS);

    if (match.kind === "text") {
      if (options.currentOnly && match.closedIssue) {
        closedDropped += 1;
        continue;
      }
      if (resolved.has(match.source.url)) continue;
      // Kept only when it really appears in the cited text.
      const verified = excerpt && match.text.includes(normalize(excerpt)) ? { excerpt } : {};
      const gap = (match.source.type === "issue" && !match.closedIssue) || (match.source.type === "readme" && "excerpt" in verified);
      resolved.set(match.source.url, { source: { ...match.source, ...verified }, strong: true, gap });
      continue;
    }
    const found = excerpt ? findInFile(match, excerpt) : null;
    // The link points at the line where the excerpt was found, never at a URL from the model.
    const url = found ? `${match.url}#L${found.line}` : match.url;
    if (resolved.has(url)) continue;
    const source: AnalysisSource = found
      ? { type: "file", url, path: match.path, line: found.line, excerpt }
      : { type: "file", url, path: match.path };
    resolved.set(url, { source, strong: found?.inCode ?? false, gap: false });
  }
  const kept = [...resolved.values()].slice(0, MAX_SOURCES_PER_ITEM);
  return {
    sources: kept.map((k) => k.source),
    supportsFact: kept.some((k) => k.strong),
    supportsGap: kept.some((k) => k.gap),
    closedDropped,
  };
}

type Label = "fact" | "inference" | "hypothesis";
// A fact needs a source that can carry it; otherwise it is at most an inference.
const groundLabel = (label: Label, resolved: Resolved): Label => (label === "fact" && !resolved.supportsFact ? "inference" : label);
const atMostInference = (label: Label): Exclude<Label, "fact"> => (label === "fact" ? "inference" : label);

// The valid items of a section, up to `max`. `dropped` counts the items left
// out because they were incomplete or reused an ID (not those over the cap).
function parseList<T extends { id: string }>(raw: unknown[], schema: z.ZodType<T>, max: number, usedIds: Set<string>) {
  const items: T[] = [];
  let dropped = 0;
  for (const entry of raw) {
    if (items.length === max) break;
    const parsed = schema.safeParse(entry);
    if (!parsed.success || usedIds.has(parsed.data.id)) {
      dropped++;
      continue;
    }
    usedIds.add(parsed.data.id);
    items.push(parsed.data);
  }
  return { items, dropped };
}

// The reply's top-level keys and the sections that may be left out on their own.
const OUTPUT_SECTIONS = ["summary", ...ANALYSIS_SECTIONS] as const;
const ISOLATABLE: ReadonlySet<string> = new Set(ANALYSIS_SECTIONS);

// The output's JSON object (the outermost braces; models sometimes add text
// around it), parsed with the narrow repair of jsonRepair.ts. If that fails,
// one broken section may be left out (parseIsolatingSection), but only for a
// complete reply: anything after its closing brace may mean it was cut off,
// and a cut-off reply is never used in part. Null when there is no object or
// it cannot be parsed without guessing.
function outputJson(output: string): { value: unknown; repairs: RepairCounts; isolated: AnalysisSection | null } | null {
  const start = output.indexOf("{");
  const end = output.lastIndexOf("}");
  if (start === -1 || end <= start) return null;
  const slice = output.slice(start, end + 1);
  const parsed = parseWithRepair(slice);
  if (parsed) return { ...parsed, isolated: null };
  if (output.slice(end + 1).trim() !== "") return null;
  const isolated = parseIsolatingSection(slice, OUTPUT_SECTIONS, ISOLATABLE);
  return isolated ? { ...isolated, isolated: isolated.isolated as AnalysisSection } : null;
}

type Unavailable = { section: AnalysisSection; reason: (typeof UNAVAILABLE_REASONS)[number] };

// The reply's sections as lists. A section left out by outputJson, missing or
// not a list is unavailable (never shown as empty). More than one unavailable
// section, or no usable summary, makes the whole reply unusable (null).
function replySections(json: NonNullable<ReturnType<typeof outputJson>>) {
  if (typeof json.value !== "object" || json.value === null || Array.isArray(json.value)) return null;
  const top = json.value as Record<string, unknown>;
  const summary = rawSummary.safeParse(top.summary);
  if (!summary.success) return null;
  const unavailable: Unavailable[] = [];
  const lists = {} as Record<AnalysisSection, unknown[]>;
  for (const section of ANALYSIS_SECTIONS) {
    const value = top[section];
    if (section === json.isolated) unavailable.push({ section, reason: "invalid_json" });
    else if (value === undefined) unavailable.push({ section, reason: "missing" });
    else if (!Array.isArray(value)) unavailable.push({ section, reason: "wrong_shape" });
    lists[section] = Array.isArray(value) && section !== json.isolated ? value : [];
  }
  if (unavailable.length > 1) return null;
  return { summary: summary.data, lists, unavailable };
}

const repairCount = (repairs: RepairCounts) => repairs.escapedQuotes + repairs.insertedCommas;

export type ParsedAnalysis = { result: AnalysisResult; repairs: RepairCounts; unavailable: Unavailable[] };

// Exported for tests. Null when the output is unusable as a whole. A repaired
// output, or one with a section left out, goes through every check below like
// any other, and the result says so. `onChecks` runs when the reply's format
// has been accepted and the evidence checks start (progress reporting).
export function parseAnalysisOutput(output: string, evidence: AnalysisEvidence, onChecks?: () => void): ParsedAnalysis | null {
  const json = outputJson(output);
  if (!json) return null;
  const reply = replySections(json);
  if (!reply) return null;
  onChecks?.();
  const repaired = repairCount(json.repairs);
  const repairNote = repaired > 0 ? [`The AI's reply had ${repaired} formatting error(s) in its JSON that were corrected automatically; its content was checked like any other reply.`] : [];
  const raw = { summary: reply.summary, ...reply.lists };
  const known = knownSources(evidence);

  const usedIds = new Set<string>();
  const dropped: Partial<Record<AnalysisSection, number>> = {};
  const list = <T extends { id: string }>(section: AnalysisSection, schema: z.ZodType<T>, max: number) => {
    const parsed = parseList(raw[section], schema, max, usedIds);
    if (parsed.dropped > 0) dropped[section] = parsed.dropped;
    return parsed.items;
  };
  const features = list("features", rawFinding, MAX_ITEMS.features);
  const limitationsRaw = list("limitations", rawFinding, MAX_ITEMS.limitations);
  const extensions = list("functionalExtensions", rawExtension, MAX_ITEMS.functionalExtensions);
  const improvements = list("technicalImprovements", rawImprovement, MAX_ITEMS.technicalImprovements);
  const projectIdeas = list("projectIdeas", rawIdea, MAX_ITEMS.projectIdeas);
  const modelLimitations = raw.evidenceLimitations.flatMap((note) => {
    const parsed = rawEvidenceLimitation.safeParse(note);
    return parsed.success ? [parsed.data] : [];
  });
  if (modelLimitations.length < raw.evidenceLimitations.length) {
    dropped.evidenceLimitations = raw.evidenceLimitations.length - modelLimitations.length;
  }

  // Limitations are current problems: closed issues are removed as sources,
  // and a limitation that rested only on closed issues is dropped.
  const limitations = limitationsRaw.flatMap((item) => {
    const resolved = resolveSources(item.sources, known, { currentOnly: true });
    if (resolved.sources.length === 0 && resolved.closedDropped > 0) return [];
    return [{ id: item.id, text: item.text, label: groundLabel(item.label, resolved), sources: resolved.sources }];
  });

  const findingIds = new Set([...features, ...limitations, ...extensions, ...improvements].map((item) => item.id));
  const keepIds = (ids: unknown[], self: string) =>
    [...new Set(ids.filter((id): id is string => typeof id === "string" && id !== self && findingIds.has(id)))];

  const toFinding = (item: z.infer<typeof rawFinding>) => {
    const resolved = resolveSources(item.sources, known, { currentOnly: false });
    return { id: item.id, text: item.text, label: groundLabel(item.label, resolved), sources: resolved.sources };
  };
  // Extensions and improvements are conclusions about current gaps: closed
  // issues are not sources, labels are never "fact", and "verified_gap" needs
  // an open issue or a verified README statement.
  const toConclusion = <T extends z.infer<typeof rawExtension> | z.infer<typeof rawImprovement>>(item: T) => {
    const resolved = resolveSources(item.sources, known, { currentOnly: true });
    return {
      id: item.id,
      title: item.title,
      text: item.text,
      label: atMostInference(item.label),
      sources: resolved.sources,
      evidenceStatus: item.evidenceStatus === "verified_gap" && resolved.supportsGap ? ("verified_gap" as const) : ("needs_investigation" as const),
      basedOn: keepIds(item.basedOn, item.id),
    };
  };

  const summary = resolveSources(raw.summary.sources, known, { currentOnly: false });
  const result: AnalysisResult = {
    version: 3,
    summary: { text: raw.summary.text, label: groundLabel(raw.summary.label, summary), sources: summary.sources },
    features: features.map(toFinding),
    limitations,
    projectIdeas: projectIdeas.map((idea) => ({
      id: idea.id,
      title: idea.title,
      problem: idea.problem,
      targetUsers: idea.targetUsers,
      solution: idea.solution,
      coreFeatures: idea.coreFeatures.slice(0, 6),
      // A reuse claim must point at something in the repository.
      reuse: idea.reuse
        .flatMap((entry) => {
          const parsedEntry = rawReuse.safeParse(entry);
          if (!parsedEntry.success) return [];
          const resolved = resolveSources(parsedEntry.data.sources, known, { currentOnly: false });
          return resolved.sources.length > 0 ? [{ text: parsedEntry.data.text, sources: resolved.sources }] : [];
        })
        .slice(0, 5),
      toBuild: idea.toBuild.slice(0, 6),
      complexity: idea.complexity,
      label: atMostInference(idea.label),
      basedOn: keepIds(idea.basedOn, idea.id),
      sources: resolveSources(idea.sources, known, { currentOnly: false }).sources,
      evidenceLimitations: idea.evidenceLimitations,
    })),
    functionalExtensions: extensions.map((item) => ({ ...toConclusion(item), userValue: item.userValue })),
    technicalImprovements: improvements.map((item) => ({ ...toConclusion(item), area: item.area })),
    // Known gaps first, then the model's own (deduplicated, capped).
    evidenceLimitations: [
      ...new Set([...repairNote, ...evidence.notes, ...promptNotes(evidence), ...modelLimitations]),
    ].slice(0, MAX_EVIDENCE_LIMITATIONS),
    sourceFiles: evidence.sourceFiles,
    // Only on partial analyses or when items were left out; complete results keep their shape.
    ...(reply.unavailable.length > 0 && { unavailableSections: reply.unavailable }),
    ...(Object.keys(dropped).length > 0 && { droppedItems: dropped }),
  };
  // Built from validated parts: a mismatch here is a server bug, not a bad request.
  const checked = analysisResultSchema.safeParse(result);
  if (!checked.success || !("version" in checked.data)) throw new Error("The analysis result does not match the result schema.");
  return { result: checked.data, repairs: json.repairs, unavailable: reply.unavailable };
}

// Exported for tests.
export function parseAnalysis(output: string, evidence: AnalysisEvidence): AnalysisResult | null {
  return parseAnalysisOutput(output, evidence)?.result ?? null;
}

// V8 JSON.parse messages that carry no text from the input; anything else
// (e.g. "Unexpected token 'x', "…" is not valid JSON") quotes the output.
const SAFE_JSON_ERRORS: [RegExp, string][] = [
  [/^Unexpected token/, "unexpected token"],
  [/^Unexpected end of JSON input/, "unexpected end of input"],
  [/^Unterminated string/, "unterminated string"],
  [/^Bad control character/, "bad control character in string"],
  [/^Bad escaped character/, "bad escaped character"],
  [/^Unexpected non-whitespace character after JSON/, "text after JSON"],
  [/^Expected property name or '\}'/, "expected property name or '}'"],
  [/^Expected ',' or '\}' after property value/, "expected ',' or '}' after property value"],
  [/^Expected ',' or '\]' after array element/, "expected ',' or ']' after array element"],
  [/^Expected ':' after property name/, "expected ':' after property name"],
  [/^Expected double-quoted property name/, "expected double-quoted property name"],
];

// Field names of the reply format: the only keys a diagnostic may name.
const OUTPUT_KEYS: ReadonlySet<string> = new Set([
  "summary", "features", "limitations", "projectIdeas", "functionalExtensions", "technicalImprovements", "evidenceLimitations",
  "id", "text", "label", "sources", "ref", "excerpt", "title", "problem", "targetUsers", "solution", "coreFeatures",
  "reuse", "toBuild", "complexity", "basedOn", "userValue", "evidenceStatus", "area",
]);

// Why parseAnalysis rejected an output, for the server log. Only categories,
// lengths, positions, field paths of the reply format and character classes:
// never any of the output's text. Exported for tests.
export function describeRejectedOutput(output: string): string {
  const length = `output ${output.length} chars`;
  const start = output.indexOf("{");
  const end = output.lastIndexOf("}");
  if (start === -1 || end <= start) return `no_json_object; ${length}`;
  const span = `object at ${start}-${end}`;
  const slice = output.slice(start, end + 1);

  const repaired = parseWithRepair(slice);
  if (!repaired) {
    let message = "";
    try {
      JSON.parse(slice);
    } catch (error) {
      message = error instanceof Error ? error.message : "";
    }
    const kind = SAFE_JSON_ERRORS.find(([pattern]) => pattern.test(message))?.[1] ?? "syntax error";
    // The position is relative to the parsed slice; report it within the whole output.
    const position = /at position (\d+)/.exec(message);
    if (!position) return `invalid_json (${kind}, position not reported; not repairable, and no single section could be left out); ${span}; ${length}`;
    const at = Number(position[1]);
    const where = `in ${jsonPathAt(slice, at, OUTPUT_KEYS)}, found ${characterClass(slice[at])}`;
    return `invalid_json (${kind}, at ${start + at}, ${where}; not repairable, and no single section could be left out); ${span}; ${length}`;
  }

  const repairs = repairCount(repaired.repairs);
  const repairedNote = repairs > 0 ? `; after ${repairs} repair(s)` : "";
  if (typeof repaired.value !== "object" || repaired.value === null || Array.isArray(repaired.value)) {
    return `schema_mismatch ((root): not an object)${repairedNote}; ${span}; ${length}`;
  }
  const top = repaired.value as Record<string, unknown>;
  const problems: string[] = [];
  const summary = rawSummary.safeParse(top.summary);
  if (!summary.success) {
    const issue = summary.error.issues[0];
    problems.push(`summary${issue.path.length ? `.${issue.path.map(String).join(".")}` : ""}: ${issue.code}`);
  }
  for (const section of ANALYSIS_SECTIONS) {
    if (top[section] === undefined) problems.push(`${section}: missing`);
    else if (!Array.isArray(top[section])) problems.push(`${section}: not a list`);
  }
  return problems.length > 0
    ? `schema_mismatch (${problems.join(", ")})${repairedNote}; ${span}; ${length}`
    : `unknown${repairedNote}; ${span}; ${length}`;
}

// Throws AppError when no usable analysis could be produced; there is no
// non-AI fallback for an analysis, so nothing is stored in that case.
// `progress` is in its "prepare" stage when called; this function reports
// "meta", "format" and "evidence" as each really starts.
export async function generateAnalysis(evidence: AnalysisEvidence, progress: ProgressReporter = noProgress): Promise<AnalysisResult> {
  const { timeoutMs, maxRetries } = metaLimits.analysis;
  const prompt = buildAnalysisPrompt(evidence);
  const sizes = promptSizes(evidence);
  console.log(
    `Analysis prompt: ${prompt.length} chars (map ${sizes.map}, readme ${sizes.readme}, issues ${sizes.issues}, files ${sizes.files} in ${evidence.files.length} files).`,
  );
  if (prompt.length > MAX_ANALYSIS_PROMPT_CHARS) {
    console.error(`Analysis prompt too large: ${prompt.length} > ${MAX_ANALYSIS_PROMPT_CHARS} chars; Meta was not called.`);
    throw new AppError(
      422,
      "ANALYSIS_PROMPT_TOO_LARGE",
      "This repository's README, issues and code are too large to analyze. No AI request was made.",
    );
  }

  let output: string;
  progress.stage("meta");
  try {
    output = await generateTracked("repository_analysis", prompt, metaLimits.analysis);
  } catch (error) {
    if (isMetaTimeout(error)) {
      console.error(`Analysis failed (timed out after ${timeoutMs} ms per attempt, ${maxRetries} retry).`);
      throw new AppError(504, "AI_ANALYSIS_TIMEOUT", "The analysis took too long. Please try again later.");
    }
    console.error(`Analysis failed (${describeMetaError(error)}).`);
    throw new AppError(502, "AI_ANALYSIS_FAILED", "The analysis could not be generated. Please try again later.");
  }

  progress.stage("format");
  const parsed = parseAnalysisOutput(output, evidence, () => progress.stage("evidence"));
  if (!parsed) {
    console.error(`Analysis returned an unusable response (${describeRejectedOutput(output)}).`);
    throw new AppError(502, "AI_ANALYSIS_INVALID", "The analysis could not be generated. Please try again later.");
  }
  if (repairCount(parsed.repairs) > 0) {
    console.log(
      `Analysis reply repaired: ${parsed.repairs.escapedQuotes} unescaped quote(s), ${parsed.repairs.insertedCommas} missing comma(s); all checks passed.`,
    );
  }
  for (const { section, reason } of parsed.unavailable) {
    console.log(`Analysis reply partial: section ${section} unavailable (${reason.replace("_", " ")}); the other sections passed every check.`);
  }
  return parsed.result;
}
