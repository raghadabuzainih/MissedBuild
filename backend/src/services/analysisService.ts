// Characters each part adds to the prompt, for the log line (numbers only).
function promptSizes(evidence: AnalysisEvidence) {
  const data = promptData(evidence);
  return {
    map: quoteForPrompt(data.map).length,
    readme: quoteForPrompt(data.readme).length,
    issues: quoteForPrompt(data.openIssues).length + quoteForPrompt(data.closedIssues).length,
    files: quoteForPrompt(data.files).length,
  };
}

// What the prompt left out, so the result does not overstate its basis.
function promptNotes(evidence: AnalysisEvidence): string[] {
  const notes: string[] = [];
  if ((evidence.readme?.content.length ?? 0) > PROMPT_README_CHARS) {
    notes.push(`Only the first ${PROMPT_README_CHARS} characters of the README were analyzed.`);
  }
  if (evidence.issues.some((issue) => (issue.body?.length ?? 0) > PROMPT_ISSUE_BODY_CHARS)) {
    notes.push(`Long issue descriptions were shortened to ${PROMPT_ISSUE_BODY_CHARS} characters.`);
  }
  return notes;
}

